# Stereochemistry: wedges, hashes, wavy, E/Z, read-back
from bondline import *
st = Style()
print("== 2-butanol")
S = Scene(st)
m = Mol(); c1 = m.atom("C", (0, 0)); c2 = m.attach(c1, 30); c3 = m.attach(c2, -30); c4 = m.attach(c3, 30)
o = m.attach(c2, 90, "OH"); m.stereo(c2, o, "wedge"); stereo_report(m)
n = m.copy(); n.stereo(n[c2], n[o], "hash"); stereo_report(n)
S.caption(m, "(<i>R</i>)"); S.caption(n, "(<i>S</i>)")
S.row([m, n]); print(S.save("butanol.png")); S.check()
print("== alanine and E/Z")
S = Scene(st)
al = Mol(); ca = al.atom("C", (0, 0)); co = al.attach(ca, -30, "CO2H"); nh = al.attach(ca, 210, "NH2"); me = al.attach(ca, 90, "Me")
al.stereo(ca, me, "hash"); stereo_report(al)
eb = Mol(); a = eb.atom("C", (0, 0)); b = eb.attach(a, 30); c = eb.attach(b, -30, order=2); d = eb.attach(c, 30); stereo_report(eb)
zb = Mol(); a = zb.atom("C", (0, 0)); b = zb.attach(a, 30); c = zb.attach(b, -30, order=2); d = zb.attach(c, -90); stereo_report(zb)
wv = Mol(); a = wv.atom("C", (0, 0)); b = wv.attach(a, 30); c = wv.attach(b, -30); x = wv.attach(b, 90, "Br"); wv.stereo(b, x, "wavy")
S.row([al, eb, zb, wv]); print(S.save("ez.png")); S.check()
print("== ring stereo")
S = Scene(st)
cy = Mol(); r = cy.ring(6, rot=90); o = cy.attach(r[0], None, "OH"); me = cy.attach(r[2], None, "Me")
cy.stereo(r[0], o, "wedge"); cy.stereo(r[2], me, "hash"); stereo_report(cy)
S.row([cy]); print(S.save("ringstereo.png")); S.check()
