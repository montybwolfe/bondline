# Stage 7: perspective rings and sandwich complexes (depth-broken lines to the ring centres), delocalised hybrids
from bondline import *

print("== metallocenes: staggered and eclipsed ferrocene, bis(benzene)chromium, acetylferrocene")
S = Scene()
f1 = Mol(); f1.sandwich("Fe")
f2 = Mol(); f2.sandwich("Fe", stagger=False)
f3 = Mol(); f3.sandwich("Cr", n=6)
f4 = Mol(); M, (top, bot) = f4.sandwich("Fe"); f4.attach(top[4], label="COMe")
S.row([f1, f2, f3, f4]); S.check(); S.save("sandwich.png")

print("== half-sandwich, piano stool and a bent metallocene")
S = Scene()
h = Mol(); M, (ring,) = h.sandwich("Fe", rings=("top",)); h.ligate(M, "sqpl", W="CO", E="CO", S="Me")
p = Mol(); cr = p.atom("Cr", (0, 0)); ar = p.persp_ring(6, (0, 1.75), toward=cr); p.deloc(ar); p.eta(cr, ar)
p.attach(cr, 270, "CO", length=1.3, free=True); p.attach(cr, 215, "CO", length=1.3, free=True, style="hash")
p.attach(cr, 325, "CO", length=1.3, free=True, style="wedge")
b = Mol(); ti, _ = b.sandwich("Ti", bend=130); b.ligate(ti, "bent", up="Cl", down="Cl")
S.row([h, p, b]); S.check(); S.save("piano.png")
print("== bent metallocenes: Schwartz's reagent, one opening to the left, one built by hand with persp_ring(toward=)")
S = Scene()
z = Mol(); zr, _ = z.sandwich("Zr", bend=130); z.ligate(zr, "bent", up="H", down="Cl")
l = Mol(); hf, _ = l.sandwich("Hf", bend=130, open=180); l.ligate(hf, "bent", up="Me", down="Me")
k = Mol(); v = k.atom("V", (0, 0))
for t in (115, 245):
    rg = k.persp_ring(5, dirv(t) * 1.75, toward=v); k.deloc(rg); k.eta(v, rg)
k.ligate(v, "lin", E="Cl")
S.row([z, l, k]); S.check(); S.save("bent.png")
print("  pieces of the line to the top ring of ferrocene:", len([b_ for b_ in f1.bonds if getattr(b_.b, "_persp3d", False)][0]._prims))

print("== delocalised hybrids: Cp-, tropylium, benzene, allyl cation and anion")
S = Scene()
cp = Mol(); cp.deloc(cp.ring(5, rot=90), charge=-1)
tr = Mol(); tr.deloc(tr.ring(7, rot=90), charge=1)
bz = Mol(); bz.deloc(bz.ring(6, rot=90))
al = Mol(); a0 = al.atom("C", (0, 0)); a1 = al.attach(a0, 30); a2 = al.attach(a1, -30); al.deloc([a0, a1, a2], charge=1)
an = Mol(); a0 = an.atom("C", (0, 0)); a1 = an.attach(a0, 30); a2 = an.attach(a1, -30); an.deloc([a0, a1, a2], charge=-1)
S.row([cp, tr, bz, al, an]); S.check(); S.save("hybrids.png")
print("  allyl bonds:", [(b_.style, b_.order) for b_ in al.bonds])

print("== checks: an eta line too short to read; a dative bond with no free partner to slide out")
S = Scene()
c1 = Mol(); M1 = c1.atom("Fe", (0, 0)); r1 = c1.ring(5, center=(0, 1.2), rot=90); c1.eta(M1, r1)
c2 = Mol(); n2 = c2.atom("N", (0, 0)); b2 = c2.atom("B", (1, 0))
for t in (90, 180, 270): c2.attach(n2, t, "Me")
for t in (0, 90, 270): c2.attach(b2, t, "F")
c2.bond(n2, b2, style="dative")
c3 = Mol(); n3 = c3.atom("N", (0, 0))
for t in (90, 180, 270): c3.attach(n3, t, "Me")
c3.attach(n3, 0, "BF3", style="dative")
S.row([c1, c2, c3]); S.check()
print("  dative bond slid out to", round(float(np.linalg.norm(c3.atoms[-1].xy - n3.xy)), 2), "BU; free:", c3.bonds[-1].free)
