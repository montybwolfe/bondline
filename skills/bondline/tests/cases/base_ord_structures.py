# Ordinary structures: chains, labels, rings, fused rings, heterocycles
from bondline import *
st = Style()
print("== chains and labels")
S = Scene(st)
m = Mol(); c = m.atom("C", (0, 0)); c2 = m.attach(c, 30); c3 = m.attach(c2, -30); m.attach(c3, -90, "OMe")
c4 = m.attach(c3, 30); m.attach(c4, 90, "O", 2); c5 = m.attach(c4, -30, "N"); m.attach(c5, -90, "Boc"); m.attach(c5, 30, "tBu")
n = Mol(); a = n.atom("C", (0, 0)); b = n.attach(a, 30, "CO2Me"); n.attach(a, 150, "Ph"); n.attach(a, -90, "NHAc")
S.caption(m, "carbamate"); S.caption(n, "ester")
S.row([m, n]); print(S.save("chains.png")); S.check()
print("== rings")
S = Scene(st)
bz = Mol(); bz.ring(6, kekule=True)
cp = Mol(); r = cp.ring(5, rot=90); cp.attach(r[0], None, "O", 2)
py = Mol(); r = py.ring(6, rot=90, labels={0: "N"}, kekule=True)
fu = Mol(); r = fu.ring(5, rot=90, labels={0: "O"}); fu.bond(r[1], r[2], 2); fu.bond(r[3], r[4], 2)
S.row([bz, cp, py, fu]); print(S.save("rings.png")); S.check()
print("== fused and substituted rings")
S = Scene(st)
nap = Mol(); r = nap.ring(6, rot=90, kekule=True); nap.ring_fuse(r[0], r[1], 6, side=-1, kekule=False)
ind = Mol(); r = ind.ring(6, rot=90, kekule=True); new = ind.ring_fuse(r[4], r[5], 5, side=-1, labels={1: "NH"})
tol = Mol(); r = tol.ring(6, rot=90, kekule=True); tol.attach(r[0], None, "Me"); tol.attach(r[3], None, "NO2")
S.row([nap, ind, tol]); print(S.save("fused.png")); S.check()
print("== spiro and bridged")
S = Scene(st)
sp = Mol(); r = sp.ring(6, rot=0); sp.ring_at(r[0], 0, 5)
S.row([sp]); print(S.save("spiro.png")); S.check()
